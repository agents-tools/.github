#!/usr/bin/env python3
"""Embed shared policy so consumers execute the implementation at their pin."""

import argparse
from pathlib import Path
import re


ROOT = Path(__file__).resolve().parents[1]
HEADER = """# Generated by Scripts/sync-policy-workflow.py; edit Scripts/check-policy.py.
# Action pins are maintained in this workflow and preserved during regeneration.
name: Shared policy

on:
  workflow_call:

permissions:
  contents: read

concurrency:
  group: shared-policy-${{ github.workflow }}-${{ github.event.pull_request.number || github.ref }}
  cancel-in-progress: true

jobs:
  policy:
    runs-on: ubuntu-24.04
    timeout-minutes: 10
    permissions:
      contents: read
    steps:
      - uses: actions/checkout@{checkout_pin}
        with:
          ref: ${{ github.event.pull_request.head.sha || github.sha }}
          fetch-depth: 0
          persist-credentials: false
      - name: Check titles, commit messages and added lines
        shell: bash
        env:
          GH_TOKEN: ${{ github.token }}
        run: |
          python3 -I - <<'PY'
"""


def render(root=ROOT):
    workflow = (root / ".github/workflows/policy.yml").read_text(encoding="utf-8")
    pins = re.findall(r"^      - uses: actions/checkout@([0-9a-f]{40} # [^\r\n]+)$",
                      workflow, re.MULTILINE)
    if len(pins) != 1:
        raise ValueError("policy.yml must contain exactly one actions/checkout full SHA pin with a version comment")
    source = (root / "Scripts/check-policy.py").read_text(encoding="utf-8")
    return HEADER.replace("{checkout_pin}", pins[0]) + "".join(
        "          " + line + "\n" if line else "\n" for line in source.splitlines()
    ) + "          PY\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    path = ROOT / ".github/workflows/policy.yml"
    try:
        expected = render()
    except (OSError, ValueError) as error:
        raise SystemExit(str(error))
    if args.check:
        if path.read_text(encoding="utf-8") != expected:
            raise SystemExit("Regenerate policy.yml with python3 Scripts/sync-policy-workflow.py")
    else:
        path.write_text(expected, encoding="utf-8")


if __name__ == "__main__":
    main()
