#!/usr/bin/env python3
"""Embed shared policy so consumers execute the implementation at their pin."""

import argparse
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
HEADER = """# Generated by Scripts/sync-policy-workflow.py; edit Scripts/check-policy.py.
name: Shared policy

on:
  workflow_call:

permissions:
  contents: read

concurrency:
  group: shared-policy-${{ github.workflow }}-${{ github.event.pull_request.number || github.ref }}
  cancel-in-progress: true

jobs:
  policy:
    runs-on: ubuntu-24.04
    timeout-minutes: 10
    permissions:
      contents: read
    steps:
      - uses: actions/checkout@08c6903cd8c0fde910a37f88322edcfb5dd907a8 # v5.0.0
        with:
          ref: ${{ github.event.pull_request.head.sha || github.sha }}
          fetch-depth: 0
          persist-credentials: false
      - name: Check titles, commit messages and added lines
        shell: bash
        run: |
          python3 -I - <<'PY'
"""


def render(root=ROOT):
    source = (root / "Scripts/check-policy.py").read_text(encoding="utf-8")
    return HEADER + "".join("          " + line + "\n" if line else "\n"
                            for line in source.splitlines()) + "          PY\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    path = ROOT / ".github/workflows/policy.yml"
    expected = render()
    if args.check:
        if not path.exists() or path.read_text(encoding="utf-8") != expected:
            raise SystemExit("Regenerate policy.yml with python3 Scripts/sync-policy-workflow.py")
    else:
        path.write_text(expected, encoding="utf-8")


if __name__ == "__main__":
    main()
